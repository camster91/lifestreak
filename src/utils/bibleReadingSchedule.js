/**
 * Get the Bible reading for a specific day of the year
 * @param {number} dayOfYear - Day of the year (1-366)
 * @returns {Object} Reading object with book, chapters, and estimated time
 */
export function getBibleReading(dayOfYear) {
  const reading = BIBLE_READING_SCHEDULE.find(r => r.day === dayOfYear);
  return reading || BIBLE_READING_SCHEDULE[0];
}

/**
 * Get an array of individual chapters from a reading
 * @param {string} chapters - Chapter range string (e.g., "22-25" or "1-4")
 * @returns {string[]} Array of chapter strings
 */
export function getChaptersList(chapters) {
  if (chapters.includes('Your choice') || chapters.includes('Key verses')) {
    return [chapters];
  }

  const match = chapters.match(/(\d+)-(\d+)/);
  if (match) {
    const start = parseInt(match[1]);
    const end = parseInt(match[2]);
    return Array.from({ length: end - start + 1 }, (_, i) => `Ch. ${start + i}`);
  }

  // Single chapter or special format
  if (chapters.includes(':')) {
    return [chapters]; // Verse range like "119:1-88"
  }

  return [`Ch. ${chapters}`];
}

/**
 * Get JW Library link for a Bible book and chapter
 * @param {string} book - Book name
 * @param {number} chapter - Chapter number
 * @returns {string} JW Library URL
 */
export function getBibleChapterLink(book, chapter) {
  const bookNum = BIBLE_BOOKS_TITLE[book];
  if (!bookNum) return 'https://www.jw.org/en/library/bible/';

  return `https://www.jw.org/en/library/bible/study-bible/books/${book.toLowerCase().replace(/\s+/g, '-')}/${chapter}/`;
}

